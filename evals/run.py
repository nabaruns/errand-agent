"""Run every eval scenario offline and write the results table.

    uv run python -m evals.run            # writes docs/eval/eval_table.md and docs/eval/results.json
"""

from __future__ import annotations

import json
import sys
import tempfile
from dataclasses import asdict, dataclass
from pathlib import Path

from .scenarios import SCENARIOS, Spec, build_env

OUT_DIR = Path(__file__).resolve().parent.parent / "docs" / "eval"


@dataclass
class Result:
    id: str
    name: str
    category: str
    expected: str
    actual: str
    passed: bool
    notes: str
    checks: list
    invariant_violations: list
    model_calls: int
    tool_calls: int


def run_one(spec: Spec) -> Result:
    with tempfile.TemporaryDirectory(prefix=f"eval-{spec.id}-") as tmp:
        env = build_env(spec, Path(tmp))
        try:
            actual = spec.fn(env)
            crash = None
        except Exception as exc:  # a crash is a failed scenario, not a failed run
            actual, crash = f"crashed: {exc!r}", repr(exc)
        violations = env.invariant_violations(spec.never_sent)
        env.close()
    failed = [label for label, ok in env.checks if not ok]
    passed = not failed and not violations and crash is None and bool(env.checks)
    notes = "; ".join([*(f"FAILED: {f}" for f in failed), *(f"INVARIANT: {v}" for v in violations),
                       *([f"CRASH: {crash}"] if crash else [])])
    if passed:
        notes = f"{len(env.checks)} checks + invariants held"
    return Result(spec.id, spec.name, spec.category, spec.expected, actual, passed, notes,
                  [{"label": label, "ok": ok} for label, ok in env.checks], violations,
                  len(env.events("model_call")), len(env.events("tool_call")))


def run_all() -> list[Result]:
    return [run_one(spec) for spec in SCENARIOS]


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def write_reports(results: list[Result], out_dir: Path = OUT_DIR) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    passed = sum(r.passed for r in results)
    lines = [
        "# Eval results",
        "",
        f"Generated by `uv run python -m evals.run` (also run by `pytest`). {passed}/{len(results)} scenarios "
        "passed. Every scenario runs offline against a scripted or recorded model with a simulated user, and is "
        "also checked against the global invariants: no side effect without a matching approval, side-effecting "
        "tools reachable only from application code, no duplicate bookings, no success reported without "
        "verification, every run ends with a reply, no injected review or forgotten/unconfirmed fact sent to "
        "the model.",
        "",
        "| # | Scenario | Category | Expected | Actual | Result | Notes |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in results:
        lines.append(f"| {r.id} | {_cell(r.name)} | {r.category} | {_cell(r.expected)} | {_cell(r.actual)} | "
                     f"{'pass' if r.passed else 'FAIL'} | {_cell(r.notes)} |")
    table = out_dir / "eval_table.md"
    table.write_text("\n".join(lines) + "\n")
    (out_dir / "results.json").write_text(json.dumps([asdict(r) for r in results], indent=1, ensure_ascii=False))
    return table


def main() -> int:
    results = run_all()
    path = write_reports(results)
    for r in results:
        print(f"{r.id} {'pass' if r.passed else 'FAIL'}  {r.name}" + ("" if r.passed else f"  -> {r.notes}"))
    print(f"\n{sum(r.passed for r in results)}/{len(results)} passed. Table: {path}")
    return 0 if all(r.passed for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
