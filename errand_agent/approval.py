"""Approval enforcement.

The model can only *propose* a side effect. Application code renders the exact
action, decides whether the user's reply is an explicit yes, and checks the
approval's fingerprint before every side-effecting tool call.
"""

from __future__ import annotations

import hashlib
import json
import re
from datetime import datetime

from .clock import IST
from .state import Request
from .store import AgentStore

# Changing any of these after approval requires a fresh approval.
MATERIAL_KEYS = ("type", "booking_id", "provider_id", "from_slot", "slot", "price")

SERVICE_LABELS = {
    "plumber": "Plumber",
    "electrician": "Electrician",
    "ac_servicing": "AC servicing",
    "carpenter": "Carpenter",
    "cleaning": "Home cleaning",
}

_AFFIRM_HEAD = r"(yes|yep|yeah|yup|y|sure|ok|okay|confirm(ed)?|go ahead|do it|book it|please do|sounds good)"
_AFFIRM_TAIL = (
    r"(\s*,?\s*(please|go ahead|confirm(ed)?|book it|do it|cancel it|reschedule it|move it|"
    r"that'?s fine|thanks|thank you))*"
)
AFFIRM = re.compile(rf"^\s*{_AFFIRM_HEAD}{_AFFIRM_TAIL}\s*[.!]*\s*$", re.IGNORECASE)
DECLINE = re.compile(r"^\s*(no|nope|nah|don'?t|do not|stop|wait|not (that|this) one)\b", re.IGNORECASE)


class ApprovalError(Exception):
    """A side effect was attempted without a valid, matching approval."""


def fingerprint(action: dict) -> str:
    material = {k: action.get(k) for k in MATERIAL_KEYS}
    return hashlib.sha256(json.dumps(material, sort_keys=True).encode()).hexdigest()[:16]


def classify_reply(text: str) -> str:
    """'affirm' only for a message that is nothing but an explicit yes; 'decline'; else 'other'."""
    if AFFIRM.match(text):
        return "affirm"
    if DECLINE.match(text):
        return "decline"
    return "other"


class ApprovalGate:
    def __init__(self, store: AgentStore) -> None:
        self.store = store

    def propose(self, session_id: str, action: dict) -> dict:
        for old in self.store.approvals_for(session_id, ("pending",)):
            self.invalidate(old["approval_id"], "superseded")
        approval_id = self.store.next_id("apv")
        return self.store.insert_approval(approval_id, session_id, action, fingerprint(action))

    def approve(self, approval_id: str) -> dict:
        approval = self.store.get_approval(approval_id)
        if approval is None or approval["status"] != "pending":
            raise ApprovalError(f"approval {approval_id} is not pending")
        self.store.update_approval(approval_id, status="approved")
        return self.store.get_approval(approval_id)

    def authorize(self, approval_id: str, action: dict) -> dict:
        """Called immediately before each side-effecting call with the exact action about to run."""
        approval = self.store.get_approval(approval_id)
        if approval is None:
            raise ApprovalError(f"no approval {approval_id}")
        if approval["status"] != "approved":
            raise ApprovalError(f"approval {approval_id} is {approval['status']}")
        if fingerprint(action) != approval["fingerprint"]:
            raise ApprovalError(f"approval {approval_id} does not cover this action (material details changed)")
        return approval

    def update_nonmaterial(self, approval_id: str, action: dict) -> None:
        """Swap bookkeeping fields (e.g. a fresh hold id at the same price) without re-approval."""
        approval = self.store.get_approval(approval_id)
        if approval is None or fingerprint(action) != approval["fingerprint"]:
            raise ApprovalError("material change needs a new approval")
        self.store.update_approval(approval_id, action=action)

    def invalidate(self, approval_id: str, reason: str) -> None:
        approval = self.store.get_approval(approval_id)
        if approval and approval["status"] in ("pending", "approved"):
            self.store.update_approval(approval_id, status="invalidated", reason=reason)

    def consume(self, approval_id: str) -> None:
        self.store.update_approval(approval_id, status="consumed")


def format_slot(slot: str) -> str:
    dt = datetime.strptime(slot, "%Y-%m-%dT%H:%M").replace(tzinfo=IST)
    return f"{dt:%a} {dt.day} {dt:%b}, {dt:%H:%M}"


def rupees(amount: int) -> str:
    return f"₹{amount:,}"


def render_prompt(action: dict, request: Request) -> str:
    """The exact text the user approves. Generated by code, never by the model."""
    service = SERVICE_LABELS.get(action["service"], action["service"])
    kind = action["type"]
    if kind == "book":
        price = rupees(action["price"])
        if action.get("previous_price") is not None:
            price += f" (was {rupees(action['previous_price'])} before the hold was renewed)"
        elif action["price"] != action.get("search_price", action["price"]):
            price += f" (search listed {rupees(action['search_price'])})"
        lines = [
            "Please confirm this booking:",
            f"- Provider: {action['provider_name']}",
            f"- Service: {service}",
            f"- When: {format_slot(action['slot'])}",
            f"- Price: {price}",
        ]
        if request.budget_max and action["price"] > request.budget_max:
            lines.append(f"- Note: this is above your {rupees(request.budget_max)} budget")
        lines.append('Reply "yes" to book it, or tell me what to change.')
    elif kind == "reschedule":
        lines = [
            "Please confirm this change:",
            f"- Booking: {action['booking_id']} with {action['provider_name']} ({service})",
            f"- From: {format_slot(action['from_slot'])}",
            f"- To: {format_slot(action['slot'])}",
            'Reply "yes" to reschedule, or tell me what to change.',
        ]
    elif kind == "cancel":
        lines = [
            "Please confirm this cancellation:",
            f"- Booking: {action['booking_id']} with {action['provider_name']} ({service})",
            f"- When: {format_slot(action['slot'])}",
            'Reply "yes" to cancel it, or tell me if you want to keep it.',
        ]
    else:
        raise ValueError(f"unknown action type {kind!r}")
    return "\n".join(lines)
